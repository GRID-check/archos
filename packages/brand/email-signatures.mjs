#!/usr/bin/env node
/**
 * Writes the founders' email signatures from identity.json, so the next rename is one edit.
 *
 *   node packages/brand/email-signatures.mjs          write signatures/<person>.html
 *   node packages/brand/email-signatures.mjs --check  fail when a written file differs
 *
 * Table layout and inline styles only, so Gmail, Apple Mail and Outlook render them alike.
 * Text only: no image, so nothing has to be hosted, and nothing breaks when a domain moves.
 * Colours are the design system's ink and ink-muted (tokens.json); the name is set like the
 * wordmark (capitals, semibold) in a font every mail client has. Paste the HTML into the mail
 * client's signature setting. Names and roles match the website's founders section.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const identity = JSON.parse(readFileSync(join(HERE, 'identity.json'), 'utf8'))

const INK = '#0f0e0d'
const INK_MUTED = '#5e5b57'

/** One row per person. `email` is the address on record; TODO(owner): company addresses once they exist. */
const PEOPLE = [
  { slug: 'jonathan-uhlemann', name: 'Jonathan Uhlemann', role: 'Architektur und Produkt', email: 'mail@jonathanuhlemann.de' },
  { slug: 'matthias-bigl', name: 'Matthias Bigl', role: 'Software und KI', email: 'mail@bigls.net' },
  { slug: 'ferdinand-rubenbauer', name: 'Ferdinand Rubenbauer', role: 'Business und Vertrieb', email: null },
]

const escape = (text) => text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')
const cell = (style, body) => `  <tr>\n    <td style="${style}">${body}</td>\n  </tr>\n`
const TEXT = `font-family:Arial,Helvetica,sans-serif;font-size:13px;line-height:18px;color:${INK_MUTED};`
const LINK = `color:${INK};text-decoration:none;`

export function signature(person) {
  const site = `https://${identity.domain}`
  return (
    `<!-- Email signature: ${escape(person.name)}. Generated by packages/brand/email-signatures.mjs from identity.json; do not edit. -->\n` +
    `<table cellpadding="0" cellspacing="0" border="0" role="presentation" style="border-collapse:collapse;max-width:100%;">\n` +
    cell(`padding:0 0 2px 0;font-family:Arial,Helvetica,sans-serif;font-size:15px;line-height:20px;color:${INK};`, escape(person.name)) +
    cell(`padding:0 0 8px 0;${TEXT}`, escape(person.role)) +
    // Every value put into the HTML below is escaped (`escape`) or a constant of this file.
    // nosemgrep: javascript.lang.security.html-in-template-string.html-in-template-string
    (person.email ? cell(`padding:0 0 2px 0;${TEXT}`, `<a href="mailto:${escape(person.email)}" style="${LINK}">${escape(person.email)}</a>`) : '') +
    cell(
      `padding:0;${TEXT}`,
      // nosemgrep: javascript.lang.security.html-in-template-string.html-in-template-string
      `<span style="font-weight:600;letter-spacing:0.02em;color:${INK};">${escape(identity.name.toUpperCase())}</span> · ` +
        // nosemgrep: javascript.lang.security.html-in-template-string.html-in-template-string
        `<a href="${escape(site)}" style="${LINK}">${escape(identity.domain)}</a> · ${escape(identity.city)}`,
    ) +
    `</table>\n`
  )
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const out = join(HERE, 'signatures')
  const check = process.argv.includes('--check')
  let stale = 0
  mkdirSync(out, { recursive: true })
  for (const person of PEOPLE) {
    const file = join(out, `${person.slug}.html`)
    const html = signature(person)
    if (!check) writeFileSync(file, html)
    else if ((() => { try { return readFileSync(file, 'utf8') } catch { return '' } })() !== html) {
      console.error(`${file} is stale: node packages/brand/email-signatures.mjs`)
      stale++
    }
  }
  if (stale) process.exit(1)
  console.log(`${PEOPLE.length} email signatures ${check ? 'up to date' : 'written'}`)
}
