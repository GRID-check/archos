/**
 * The door's guide, glossary and prompts are Markdown files beside this spec,
 * written and reviewed as text. The server cannot read files at run time in
 * every build (webpack, turbopack and vitest each load differently), so their
 * text is embedded in `docs.generated.ts`, which this spec writes and checks:
 *
 *   UPDATE_FIXTURES=1 bunx vitest run src/lib/agent-api/door/docs.spec.ts
 *
 * Edit the Markdown, never the generated module.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'
import { describe, expect, it } from 'vitest'

const DIR = join(process.cwd(), 'src/lib/agent-api/door')
const GENERATED = join(DIR, 'docs.generated.ts')

function markdownFiles(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true })
    .flatMap((entry) => (entry.isDirectory() ? markdownFiles(join(dir, entry.name)) : entry.name.endsWith('.md') ? [join(dir, entry.name)] : []))
    .sort()
}

function render(): string {
  const entries = markdownFiles(DIR).map((file) => `  ${JSON.stringify(relative(DIR, file))}: ${JSON.stringify(readFileSync(file, 'utf8'))},`)
  return (
    '// Generated by src/lib/agent-api/door/docs.spec.ts from the Markdown files beside it. Do not edit;\n' +
    '// edit the Markdown and run: UPDATE_FIXTURES=1 bunx vitest run src/lib/agent-api/door/docs.spec.ts\n\n' +
    `export const DOOR_DOCS = {\n${entries.join('\n')}\n} as const\n\nexport type DoorDoc = keyof typeof DOOR_DOCS\n`
  )
}

describe('the door docs module', () => {
  it('embeds the Markdown files as they are', () => {
    const rendered = render()
    if (process.env.UPDATE_FIXTURES === '1') writeFileSync(GENERATED, rendered)
    expect(readFileSync(GENERATED, 'utf8')).toBe(rendered)
  })
})
